export type AgeGroupKey = '17-21' | '22-26' | '27-31' | '32-36' | '37-41' | '42-46' | '47-51' | '52-56' | '57-61' | 'Over 62';

export const AGE_GROUP_KEYS: AgeGroupKey[] = [
  '17-21', '22-26', '27-31', '32-36', '37-41', '42-46', '47-51', '52-56', '57-61', 'Over 62'
];

export function normalizeAgeGroup(ageOrGroup: number | string): AgeGroupKey {
  if (typeof ageOrGroup === 'number') {
    if (ageOrGroup <= 21) return '17-21';
    if (ageOrGroup <= 26) return '22-26';
    if (ageOrGroup <= 31) return '27-31';
    if (ageOrGroup <= 36) return '32-36';
    if (ageOrGroup <= 41) return '37-41';
    if (ageOrGroup <= 46) return '42-46';
    if (ageOrGroup <= 51) return '47-51';
    if (ageOrGroup <= 56) return '52-56';
    if (ageOrGroup <= 61) return '57-61';
    return 'Over 62';
  }
  const str = String(ageOrGroup).trim();
  if (str === '62+' || str === 'Over 62' || str.includes('62')) return 'Over 62';
  if (AGE_GROUP_KEYS.includes(str as AgeGroupKey)) return str as AgeGroupKey;
  return '22-26';
}

