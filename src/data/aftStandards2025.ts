// Precise score evaluator by interpolating against the official table points
export function calculateOfficialAftScore(
  eventCode: string,
  rawVal: number,
  ageGroup: string
): number {
  if (isNaN(rawVal) || rawVal <= 0) return 0;
  const ageKey = normalizeAgeGroup(ageGroup);

  let table: Record<number, Record<AgeGroupKey, number>>;
  let isHigherBetter = true;

  switch (eventCode) {
    case 'MDL':
      table = MDL_MALE_TABLE;
      isHigherBetter = true;
      break;
    case 'HRP':
      table = HRP_MALE_TABLE;
      isHigherBetter = true;
      break;
    case 'SDC':
      table = SDC_MALE_TABLE;
      isHigherBetter = false;
      break;
    case 'PLK':
      table = PLK_MALE_TABLE;
      isHigherBetter = true;
      break;
    case '2MR':
      table = TWO_MILE_RUN_MALE_TABLE;
      isHigherBetter = false;
      break;
    default:
      return 0;
  }

  // Sorted point breakpoints in descending order: 100, 99, 98, ...
  const points = Object.keys(table).map(Number).sort((a, b) => b - a);

  // Check top score (100 pts)
  const topThreshold = table[100][ageKey];
  if (isHigherBetter ? rawVal >= topThreshold : rawVal <= topThreshold) {
    return 100;
  }

  // Check lowest score (0 pts)
  const bottomThreshold = table[0][ageKey];
  if (isHigherBetter ? rawVal <= bottomThreshold : rawVal >= bottomThreshold) {
    return 0;
  }

  // Bracket search for precise interpolation
  for (let i = 0; i < points.length - 1; i++) {
    const pHigh = points[i];
    const pLow = points[i + 1];
    const vHigh = table[pHigh][ageKey];
    const vLow = table[pLow][ageKey];

    if (isHigherBetter) {
      if (rawVal <= vHigh && rawVal >= vLow) {
        if (vHigh === vLow) return pHigh;
        const ratio = (rawVal - vLow) / (vHigh - vLow);
        return Math.round(pLow + ratio * (pHigh - pLow));
      }
    } else {
      // Time events (lower is better)
      if (rawVal >= vHigh && rawVal <= vLow) {
        if (vHigh === vLow) return pHigh;
        const ratio = (vLow - rawVal) / (vLow - vHigh);
        return Math.round(pLow + ratio * (pHigh - pLow));
      }
    }
  }

  return 0;
}

// Get the exact minimum passing standard (60 pts) from the official table
export function getOfficialPassingStandard(
  eventCode: string,
  ageGroup: string
): string {
  const ageKey = normalizeAgeGroup(ageGroup);
  switch (eventCode) {
    case 'MDL':
      return `${MDL_MALE_TABLE[60][ageKey]}`;
    case 'HRP':
      return `${HRP_MALE_TABLE[60][ageKey]}`;
    case 'SDC':
      return formatSecondsToTime(SDC_MALE_TABLE[60][ageKey]);
    case 'PLK':
      return formatSecondsToTime(PLK_MALE_TABLE[60][ageKey]);
    case '2MR':
      return formatSecondsToTime(TWO_MILE_RUN_MALE_TABLE[60][ageKey]);
    default:
      return '';
  }
}

// Format seconds to mm:ss
export function formatSecondsToTime(totalSecs: number): string {
  const mins = Math.floor(totalSecs / 60);
  const secs = totalSecs % 60;
  return `${mins}:${secs.toString().padStart(2, '0')}`;
}
